CREATE TABLE IF NOT EXISTS native_candidate_job_attempts (
 tenant_id TEXT NOT NULL,
 job_id TEXT NOT NULL,
 attempt_id TEXT NOT NULL,
 run_id TEXT NOT NULL,
 attempt_generation INTEGER NOT NULL CHECK(attempt_generation>0),
 job_attempt_version INTEGER NOT NULL CHECK(job_attempt_version>0),
 fence_token TEXT NOT NULL,
 eligibility_operation_id TEXT NOT NULL,
 eligibility_generation INTEGER NOT NULL CHECK(eligibility_generation>0),
 source_repository_id TEXT NOT NULL,
 target_repository_id TEXT NOT NULL,
 pull_request_id TEXT NOT NULL,
 pull_request_version INTEGER NOT NULL CHECK(pull_request_version>0),
 issue_version INTEGER NOT NULL CHECK(issue_version>0),
 producer_id TEXT NOT NULL,
 producer_auth_epoch INTEGER NOT NULL CHECK(producer_auth_epoch>0),
 tenant_policy_epoch INTEGER NOT NULL CHECK(tenant_policy_epoch>0),
 context TEXT NOT NULL,
 candidate_sha TEXT NOT NULL,
 head_sha TEXT NOT NULL,
 base_sha TEXT NOT NULL,
 candidate_tree_sha TEXT NOT NULL,
 policy_digest TEXT NOT NULL,
 plan_digest TEXT NOT NULL,
 reviewed_diff_digest TEXT NOT NULL,
 image_digest TEXT NOT NULL,
 command_digest TEXT NOT NULL,
 command_json TEXT NOT NULL CHECK(json_valid(command_json)),
 candidate_artifacts_json TEXT NOT NULL CHECK(json_valid(candidate_artifacts_json)),
 observed_rules_json TEXT NOT NULL CHECK(json_valid(observed_rules_json)),
 state TEXT NOT NULL CHECK(state IN('queued','in_progress','completed','failed','cancelled','timed_out')),
 cancel_requested INTEGER NOT NULL DEFAULT 0 CHECK(cancel_requested IN(0,1)),
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL,
 expires_at TEXT NOT NULL,
 receipt_json TEXT CHECK(receipt_json IS NULL OR json_valid(receipt_json)),
 receipt_sha256 TEXT,
 finalization_nonce TEXT,
 PRIMARY KEY(tenant_id,attempt_id),
 UNIQUE(tenant_id,job_id,attempt_generation),
 FOREIGN KEY(tenant_id,run_id) REFERENCES runs(tenant_id,id),
 FOREIGN KEY(tenant_id,job_id) REFERENCES jobs(tenant_id,id),
 FOREIGN KEY(tenant_id,attempt_id) REFERENCES job_attempts(tenant_id,id),
 FOREIGN KEY(tenant_id,eligibility_operation_id) REFERENCES pr_eligibility_generations(tenant_id,operation_id),
 FOREIGN KEY(tenant_id,producer_id) REFERENCES principals(tenant_id,id)
);

